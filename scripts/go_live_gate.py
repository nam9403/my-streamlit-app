#!/usr/bin/env python3
"""
Go-live operational gate runner.

Purpose:
- Convert GO_LIVE_RUNBOOK pre-release checks into a repeatable command.
- Emit machine-readable + human-readable artifacts for release evidence.

Usage:
  python scripts/go_live_gate.py
  python scripts/go_live_gate.py --env preprod --dry-run
  python scripts/go_live_gate.py --skip-uat
"""
from __future__ import annotations

import argparse
import json
import os
import subprocess
import sys
import time
from datetime import datetime, timezone
from pathlib import Path
from typing import Any

ROOT = Path(__file__).resolve().parent.parent
ARTIFACT_DIR = ROOT / "artifacts" / "operations"
SUMMARY_JSON = ARTIFACT_DIR / "go_live_gate_summary.json"
SUMMARY_MD = ARTIFACT_DIR / "go_live_gate_summary.md"


def _resolve_env(name: str) -> str:
    value = str(name or "").strip().lower()
    if value in ("prod", "production"):
        return "prod"
    if value in ("preprod", "staging", "stage"):
        return "preprod"
    return "dev"


def _run(cmd: list[str], *, env: dict[str, str], dry_run: bool) -> tuple[int, float]:
    print(f"> {' '.join(cmd)}")
    started = time.perf_counter()
    if dry_run:
        return 0, (time.perf_counter() - started) * 1000.0
    out = subprocess.run(cmd, cwd=str(ROOT), env=env)
    return int(out.returncode), (time.perf_counter() - started) * 1000.0


def _render_markdown(summary: dict[str, Any]) -> str:
    lines: list[str] = []
    lines.append("# Go-Live Gate Summary")
    lines.append("")
    lines.append(f"- Generated at (UTC): `{summary['generated_at_utc']}`")
    lines.append(f"- Env: `{summary['env']}`")
    lines.append(f"- Dry run: `{summary['dry_run']}`")
    lines.append(f"- Decision: `{summary['decision']}`")
    lines.append("")
    lines.append("## Steps")
    lines.append("")
    for row in summary.get("steps", []):
        status = "PASS" if int(row.get("exit_code") or 0) == 0 else "FAIL"
        cmd = str(row.get("command") or "")
        elapsed = float(row.get("elapsed_ms") or 0.0)
        lines.append(f"- [{status}] `{cmd}` ({elapsed:.1f} ms)")
    lines.append("")
    lines.append("## Notes")
    lines.append("")
    lines.append("- This artifact is generated by `scripts/go_live_gate.py`.")
    lines.append("- Use together with `GO_LIVE_RUNBOOK.md` manual sign-off steps.")
    return "\n".join(lines) + "\n"


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--env", default=str(os.environ.get("II_ENV") or "preprod"))
    parser.add_argument("--dry-run", action="store_true")
    parser.add_argument("--skip-uat", action="store_true")
    parser.add_argument("--skip-prod-readiness", action="store_true")
    parser.add_argument("--skip-dss-gate", action="store_true")
    parser.add_argument("--skip-smart-money-sync", action="store_true")
    parser.add_argument("--skip-live-stability", action="store_true")
    parser.add_argument("--skip-runtime-alert-guard", action="store_true")
    parser.add_argument("--min-cx-samples", type=int, default=20)
    args = parser.parse_args()

    env_name = _resolve_env(str(args.env))
    env = os.environ.copy()
    env["II_ENV"] = env_name
    env.setdefault("II_LOG_JSON", "1")
    env.setdefault("II_REQUIRE_APP_SECRET_KEY", "1")

    commands: list[list[str]] = [
        [sys.executable, str(ROOT / "scripts" / "preflight_check.py"), "--prod"],
        [sys.executable, str(ROOT / "scripts" / "scale_gate_check.py"), "--min-cx-samples", str(max(0, int(args.min_cx_samples))), "--require-go"],
        [sys.executable, str(ROOT / "scripts" / "slo_gate_check.py"), "--min-cx-samples", str(max(0, int(args.min_cx_samples))), "--require-go"],
    ]
    if not bool(args.skip_prod_readiness):
        commands.insert(
            1,
            [
                sys.executable,
                str(ROOT / "scripts" / "prod_readiness_check.py"),
                "--env",
                env_name,
                "--require-go",
                "--require-live-data",
                "--min-cx-samples",
                str(max(0, int(args.min_cx_samples))),
            ],
        )
    if not bool(args.skip_dss_gate):
        commands.insert(
            2,
            [
                sys.executable,
                str(ROOT / "scripts" / "dss_release_gate.py"),
                "--symbol",
                "FPT",
                "--user-id",
                "default_user",
                "--strict",
            ],
        )
    if not bool(args.skip_smart_money_sync):
        commands.insert(
            3,
            [
                sys.executable,
                str(ROOT / "scripts" / "smart_money_event_sync.py"),
                "--symbols",
                "FPT,VNM,HPG,VCB",
            ],
        )
    if not bool(args.skip_uat):
        commands.append([sys.executable, str(ROOT / "scripts" / "uat_gate.py")])
    if not bool(args.skip_live_stability):
        commands.append(
            [
                sys.executable,
                str(ROOT / "scripts" / "live_data_stability_benchmark.py"),
                "--window-days",
                "14",
                "--min-sessions",
                "7",
                "--require-go",
            ]
        )
    if not bool(args.skip_runtime_alert_guard):
        commands.append(
            [
                sys.executable,
                str(ROOT / "scripts" / "runtime_alert_guard.py"),
                "--notify-on",
                "critical",
                "--out",
                str(ROOT / "artifacts" / "operations" / "runtime_alert_guard_go_live.json"),
            ]
        )

    step_rows: list[dict[str, Any]] = []
    failed = False
    for cmd in commands:
        rc, elapsed_ms = _run(cmd, env=env, dry_run=bool(args.dry_run))
        step_rows.append({"command": " ".join(cmd), "exit_code": rc, "elapsed_ms": round(elapsed_ms, 2)})
        if rc != 0:
            failed = True
            break

    summary = {
        "generated_at_utc": datetime.now(timezone.utc).isoformat(),
        "env": env_name,
        "dry_run": bool(args.dry_run),
        "decision": "PASS" if not failed else "FAIL",
        "steps": step_rows,
    }

    ARTIFACT_DIR.mkdir(parents=True, exist_ok=True)
    SUMMARY_JSON.write_text(json.dumps(summary, ensure_ascii=False, indent=2), encoding="utf-8")
    SUMMARY_MD.write_text(_render_markdown(summary), encoding="utf-8")
    print(f"[OK] Wrote {SUMMARY_JSON}")
    print(f"[OK] Wrote {SUMMARY_MD}")

    return 0 if not failed else 2


if __name__ == "__main__":
    raise SystemExit(main())

